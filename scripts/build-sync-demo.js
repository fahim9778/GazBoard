#!/usr/bin/env node
// Fold the sync bench into one file that runs anywhere Node does.
//
// The point is the second machine. Asking someone to clone a repo and install
// dependencies before they can find out whether their wifi carries a packet is
// a poor trade; the sync code uses only Node built-ins, so it can just as well
// be one file on a USB stick.
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

/** Wrap a CommonJS file so it can live beside others in one script. */
function wrap(name, src) {
  return `__mod['${name}'] = function (module, exports, require) {\n${src}\n};\n`;
}

const out = `#!/usr/bin/env node
/*
 * GazBoard LAN sync — standalone bench.
 *
 * Built from sync/protocol.js, sync/node.js and scripts/sync-demo.js.
 * Do not edit this file; edit those and run: node scripts/build-sync-demo.js
 *
 * No dependencies. Node 18 or newer, and nothing else.
 *
 *   node gazboard-sync.js receive
 *   node gazboard-sync.js send <address> <code> [board.gazboard]
 *   node gazboard-sync.js discover
 */
'use strict';

const __mod = {};
const __cache = {};
function __require(name) {
  const key = name.replace(/^\\.\\.?\\//, '').replace(/^sync\\//, '').replace(/\\.js$/, '');
  if (__cache[key]) return __cache[key].exports;
  if (!__mod[key]) return require(name);
  const m = { exports: {} };
  __cache[key] = m;
  __mod[key](m, m.exports, __require);
  return m.exports;
}

${wrap('protocol', read('sync/protocol.js'))}
${wrap('node', read('sync/node.js'))}

;(function (module, exports, require) {
${read('scripts/sync-demo.js').replace(/^#!.*\n/, '')}
})({ exports: {} }, {}, __require);
`;

const dest = path.join(root, 'dist-sync', 'gazboard-sync.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${dest}  (${(out.length / 1024).toFixed(1)} KB, no dependencies)`);
